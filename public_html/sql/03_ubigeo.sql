-- =====================================================================
-- 03_ubigeo.sql — Catálogo geográfico del Perú
-- Ejecutar después de 01_esquema.sql y 02_catalogos.sql.
--
-- Fuente de los datos: adaptado del volcado público de INEI publicado en
-- el repositorio joseluisq/ubigeos-peru (2015), con dos correcciones:
--   1. La Provincia Constitucional del Callao, que en esa fuente aparecía
--      mal anidada como provincia de Lima, se reubicó como su propio
--      departamento con el código UBIGEO oficial 07 (así lo trata el
--      INEI: Lima=15 y Callao=07 son entidades de primer nivel distintas).
--   2. Se añadió el distrito "Mi Perú" (Callao), creado en 2014 por la
--      Ley N.° 30197 y por tanto ausente del volcado original de 2015.
--
-- Se agrega además un departamento 26 "Sin definir" (ubigeo '00'): es el
-- valor por defecto para leads del formulario público /registrar cuando
-- el gestor no completó el distrito (ese campo es opcional, ver §7A),
-- ya que departamento_id es NOT NULL en une_negocios. El equipo lo
-- reemplaza por la ubicación real al llamar al lead. Ver
-- DEPARTAMENTO_SIN_DEFINIR_ID en config/config.php.
--
-- Resultado: 25 departamentos reales + 1 "Sin definir", 194 provincias,
-- 1834 distritos. Es un
-- catálogo vivo: el INEI ha creado nuevos distritos desde 2015 (la cifra
-- de referencia actual ronda los 1874). No inventes registros para
-- cuadrar esa cifra: agrega o corrige puntualmente desde admin/ubigeo.php
-- a medida que el equipo detecte un distrito faltante o un nombre
-- desactualizado en el trabajo de campo.
-- =====================================================================

CREATE TABLE une_departamentos (
  id      SMALLINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  ubigeo  CHAR(2) NOT NULL UNIQUE,
  nombre  VARCHAR(60) NOT NULL,
  activo  TINYINT(1) NOT NULL DEFAULT 1
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE une_provincias (
  id               MEDIUMINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  departamento_id  SMALLINT UNSIGNED NOT NULL,
  ubigeo           CHAR(4) NOT NULL UNIQUE,
  nombre           VARCHAR(80) NOT NULL,
  activo           TINYINT(1) NOT NULL DEFAULT 1,
  INDEX idx_departamento (departamento_id),
  CONSTRAINT fk_provincia_departamento FOREIGN KEY (departamento_id)
    REFERENCES une_departamentos (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

CREATE TABLE une_distritos (
  id            MEDIUMINT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  provincia_id  MEDIUMINT UNSIGNED NOT NULL,
  ubigeo        CHAR(6) NOT NULL UNIQUE,
  nombre        VARCHAR(80) NOT NULL,
  activo        TINYINT(1) NOT NULL DEFAULT 1,
  INDEX idx_provincia (provincia_id),
  INDEX idx_nombre (nombre),
  CONSTRAINT fk_distrito_provincia FOREIGN KEY (provincia_id)
    REFERENCES une_provincias (id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

SET NAMES utf8mb4;


